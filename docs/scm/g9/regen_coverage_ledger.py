def stamp_fixture_provenance(rows: list, source: dict) -> None:
    for row in rows:
        if row["status"] == "unresolved":
            continue
        for p in row["phases"]:
            extracted = independent_finite_set(row["comm_id"], p["phase_id"], source, p)
            labels = bearing_labels(p)
            independent = (
                extracted is not None and set(labels) <= set(extracted) and len(labels) > 0
            )
            provenance = (
                "independently-extracted-source" if independent else "g9-ledger-declaration"
            )
            for v in p.get("fixture_vectors") or []:
                v["finite_branch_provenance"] = provenance
            p["finite_branch_provenance"] = provenance


def source_validation_record(row: dict, phase: dict, source: dict) -> dict:
    comm_id = row["comm_id"]
    phase_id = phase["phase_id"]
    extracted = independent_finite_set(comm_id, phase_id, source, phase)
    labels = bearing_labels(phase)
    cap_mod = phase.get("capture_module", "")
    cap_path = resolve_capture_path(cap_mod)
    mismatch = None
    strategy = phase.get("capture_strategy") or "existing-local-boundary"
    audit = PHASE_SOURCE_AUDITS.get((comm_id, phase_id))
    if strategy == "no-lawful-boundary":
        mode = "unresolved"
        comparison = "no-lawful-boundary"
        mismatch = {"capture_strategy": strategy}
    elif extracted is not None:
        mode = "source-extracted"
        if set(labels) <= set(extracted):
            comparison = "bearing-labels-subset-of-independently-extracted-set"
        else:
            comparison = "bearing-labels-mismatch-independently-extracted-set"
            mismatch = {
                "ledger_labels": labels,
                "extracted": extracted,
                "extra_in_ledger": sorted(set(labels) - set(extracted)),
            }
    elif strategy == "planned-typed-hook":
        mode = "manual-source-audit"
        comparison = "planned-typed-hook-live-boundary-verified"
        mismatch = None
    elif audit and audit["validation_mode"] == "manual-source-audit":
        mode = "manual-source-audit"
        comparison = audit["comparison_result"]
        mismatch = audit.get("mismatch")
    elif cap_path is not None and cap_path.is_dir():
        mode = "structural"
        comparison = "directory-module-existence-only"
    elif cap_path is not None and cap_path.is_file():
        token_hit = capture_symbol_in_module(phase.get("capture_symbol", ""), cap_path)
        mode = "structural"
        comparison = (
            "capture-module-file-exists-and-token-present"
            if token_hit
            else "capture-module-file-exists-token-absent"
        )
        if not token_hit:
            mismatch = {"capture_symbol": phase.get("capture_symbol")}
    else:
        mode = "structural"
        comparison = "no-independent-extract-and-no-resolvable-module-file"
        mismatch = {"capture_module": cap_mod}
    rec = {
        "comm_id": comm_id,
        "phase_id": phase_id,
        "source_module": cap_mod,
        "owning_symbol": phase.get("capture_symbol"),
        "exact_live_operation_or_callback": phase.get("aggregate_member_or_capture_site_id"),
        "success_boundary": (
            (audit or {}).get("success_boundary") or phase.get("success_predicate")
        ),
        "independently_extracted_finite_set": extracted,
        "ledger_bearing_labels": labels,
        "comparison_result": comparison,
        "validation_mode": mode,
        "unresolved_mismatch": mismatch,
        "capture_strategy": strategy,
    }
    if audit:
        if audit.get("call_sites"):
            rec["call_sites"] = audit["call_sites"]
        if audit.get("capture_correction"):
            rec["capture_correction"] = audit["capture_correction"]
    return rec


