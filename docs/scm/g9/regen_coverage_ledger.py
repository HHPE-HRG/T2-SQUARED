def resolve_capture_path(capture_module: str) -> Path | None:
    rel = capture_module.split("#", 1)[0]
    if rel in {"none", "live-code"}:
        return None
    path = ROOT / rel
    return path if path.exists() else None


def capture_symbol_in_module(symbol: str, path: Path) -> bool:
    """Token presence in a file. Directories never count as a hit."""
    if symbol == "none":
        return True
    if path.is_dir():
        return False
    text = path.read_text(errors="ignore")
    tokens = re.findall(r"[A-Za-z_][A-Za-z0-9_.]{2,}", symbol)
    if not tokens:
        return False
    return any(tok.split(".")[-1] in text or tok in text for tok in tokens)


