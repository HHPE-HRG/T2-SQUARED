def fixture_id(comm_id: str, phase_id: str, req: str, st: str) -> str:
    safe = lambda s: re.sub(r"[^A-Za-z0-9._-]+", "_", s)
    return f"fx.{comm_id}.{phase_id}.{safe(req)}__{safe(st)}"


def equality_mapping(semantic_kind: str, a_field: str) -> dict:
    if semantic_kind not in {"request", "state"}:
        raise ValueError(f"semanticKind must be request|state, got {semantic_kind}")
    domain = "request_label" if semantic_kind == "request" else "state_label"
    rule = f"A.{a_field} = {domain}"
    return {
        "equality_bearing_side": semantic_kind,
        "A_field": a_field,
        "finite_domain": domain,
        "rule": rule,
    }


def phase(
    *,
    phase_id: str,
    family: str,
    capture_symbol: str,
    capture_module: str,
    aggregate_member_or_capture_site_id: str,
    success_predicate: str,
    equality_type: str,
    equality_projection: list[str],
    live_to_equality: str,
    shadow_to_equality: str,
    semantic_kind: str,
    request_label: list[str] | str,
    state_label: list[str] | str,
    live_failure_no_capture_disposition: str,
    sensitive_data_exclusions: list[str] | None = None,
    retain: bool,
    retain_rationale: str,
    comm_id: str,
    notes: str | None = None,
    counted_fixtures: bool = True,
    capture_strategy: str = "existing-local-boundary",
    fixture_driver_class: str | None = None,
):
    """Build one ledger phase + counted fixture vectors.

    Agent: `fixture_driver_class == "declaration-absence"` selects WP8 declaration
    drivers (no invented live writer). Do not key absence on request_label
    CANONICAL_ABSENCE alone — that label is shared by many live-success phases.
    """
    del live_to_equality, shadow_to_equality
    disp = live_failure_no_capture_disposition
    # Auto-mark fixture-only / no-live-writer declaration phases for WP8.
    if fixture_driver_class is None and (
        "fixture-only" in disp or "no-live-writer" in disp
    ):
        fixture_driver_class = "declaration-absence"
    req = [request_label] if isinstance(request_label, str) else list(request_label)
    st = [state_label] if isinstance(state_label, str) else list(state_label)
    a_field = equality_projection[0]
    mapping = equality_mapping(semantic_kind, a_field)
    # Agent: declaration-absence and dormant-prototype vectors copy phase law
    # (not success-path). Live-success vectors keep success-path.
    vector_disp = (
        disp
        if fixture_driver_class in ("declaration-absence", "dormant-prototype")
        else "success-path"
    )
    vectors = []
    if counted_fixtures:
        for r in req:
            for s in st:
                fid = fixture_id(comm_id, phase_id, r, s)
                a_value = r if semantic_kind == "request" else s
                vectors.append(
                    {
                        "fixture_id": fid,
                        "phase": phase_id,
                        "bounded_live_projection": {a_field: a_value},
                        "expected_equality_A": {a_field: a_value},
                        "expected_semanticKind": semantic_kind,
                        "expected_request_label": r,
                        "expected_state_label": s,
                        "expected_retention": retain,
                        "expected_live_failure_no_capture_disposition": vector_disp,
                    }
                )
    obj = {
        "phase_id": phase_id,
        "family": family,
        "capture_symbol": capture_symbol,
        "capture_module": capture_module,
        "aggregate_member_or_capture_site_id": aggregate_member_or_capture_site_id,
        "success_predicate": success_predicate,
        "equality_type": equality_type,
        "equality_projection_A": [a_field],
        "liveToEquality": mapping,
        "shadowToEquality": mapping,
        "semanticKind": semantic_kind,
        "request_label": req,
        "state_label": st,
        "live_failure_no_capture_disposition": live_failure_no_capture_disposition,
        "sensitive_data_exclusions": sensitive_data_exclusions or list(DEFAULT_EXCLUSIONS),
        "retainCurrentAfterPublish": retain,
        "retainCurrentAfterPublish_rationale": retain_rationale,
        "fixture_ids": [v["fixture_id"] for v in vectors],
        "fixture_vectors": vectors,
        "counted_fixtures": counted_fixtures,
        "capture_strategy": capture_strategy,
    }
    if fixture_driver_class is not None:
        obj["fixture_driver_class"] = fixture_driver_class
    if notes:
        obj["notes"] = notes
    if not counted_fixtures:
        obj["inventory_mismatch_evidence"] = True
    return obj


