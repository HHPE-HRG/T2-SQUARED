def _is_auto_changelog_bullet(line: str) -> bool:
    stripped = line.strip()
    if not stripped.startswith("- "):
        return False
    return any(stripped.startswith(prefix) for prefix in _CHANGELOG_AUTO_PREFIXES)


def _section_body(text: str, heading: str) -> str:
    marker = f"## {heading}"
    start = text.find(marker)
    if start < 0:
        return ""
    start += len(marker)
    rest = text[start:]
    nxt = re.search(r"\n## ", rest)
    return rest[: nxt.start()] if nxt else rest


def extract_retained_changelog_notes(prior: str) -> list[str]:
    """Collect curated notes: explicit Retained section + migrate non-auto design-approved bullets."""
    notes: list[str] = []
    seen: set[str] = set()

    def add(line: str) -> None:
        item = line.strip()
        if not item or item in seen:
            return
        if item == "- (none)":
            return
        # Phase-list machine line alone is not retained; keep curated suffixes as notes.
        if item == "- No phase-id changes.":
            return
        if item.startswith("- No phase-id changes.") and "FILE-LOGS" in item:
            item = "- FILE-LOGS equality projection is `member_id` (request-side)."
        seen.add(item)
        notes.append(item)

    retained_body = _section_body(prior, "Retained notes")
    for line in retained_body.splitlines():
        if line.strip().startswith("- "):
            add(line)

    # Migrate prior design-approved bullets that are not auto-generated.
    if prior.startswith("# G9 design-approved changelog"):
        design_end = len(prior)
        for marker in (
            "\n## Retained notes",
            "\n## Phase list changes this regen",
            "\n## Historical freeze-candidate regeneration",
        ):
            idx = prior.find(marker)
            if idx >= 0:
                design_end = min(design_end, idx)
        for line in prior[:design_end].splitlines():
            if line.strip().startswith("- ") and not _is_auto_changelog_bullet(line):
                add(line)

    # Migrate curated clause from old phase-list line.
    phase_body = _section_body(prior, "Phase list changes this regen")
    for line in phase_body.splitlines():
        if "FILE-LOGS" in line:
            add(line)

    return notes


def write_changelog(ledger, report, old=None):
    # Agent RFC-022: retain curated notes; skip write when rendered text is unchanged (WP8 no-diff).
    old = old or {}
    old_by = {r["comm_id"]: r for r in old.get("rows") or []}
    new_by = {r["comm_id"]: r for r in ledger["rows"]}
    diffs = []
    for comm_id in sorted(set(old_by) | set(new_by)):
        old_phases = [p["phase_id"] for p in (old_by.get(comm_id) or {}).get("phases") or []]
        new_phases = [p["phase_id"] for p in (new_by.get(comm_id) or {}).get("phases") or []]
        if old_phases == new_phases:
            continue
        removed = [p for p in old_phases if p not in new_phases]
        added = [p for p in new_phases if p not in old_phases]
        diffs.append(
            f"- `{comm_id}`: before {old_phases or '[]'}; after {new_phases or '[]'}; "
            f"removed {removed or '[]'}; added {added or '[]'}."
        )
    prev_fx = old.get("counted_fixture_vector_count")
    changelog_path = ROOT / "docs/scm/g9/coverage-changelog.md"
    prior = changelog_path.read_text(encoding="utf-8") if changelog_path.exists() else ""
    historical = ""
    if prior.startswith("# G9 design-freeze-candidate changelog"):
        historical = "\n## Historical freeze-candidate regeneration\n\n" + prior
    elif "## Historical freeze-candidate regeneration" in prior:
        idx = prior.find("## Historical freeze-candidate regeneration")
        historical = "\n" + prior[idx:]
    retained = extract_retained_changelog_notes(prior)
    try:
        authorized = resolve_implementation_authorized()
    except AuthorizationError:
        authorized = False
    lines = [
        "# G9 design-approved changelog",
        "",
        "<!-- Agent: design approved 2026-09-30. Planning authorized. No G9 runtime in this regen. -->",
        "",
        (
            "- Status `design-approved`. writing_plans_authorized=true. "
            f"implementation_authorized={str(report.get('implementation_authorized')).lower()} "
            "(RFC-022: derived from validated authorization.md body)."
        ),
        (
            "- Did not create docs/scm/g9/authorization.md."
            if not authorized
            else "- authorization.md present and valid; regen emits implementation_authorized=true."
        ),
        "- INV-T2-ORCH-QUEUE / queue-offered ledger equality_type is G9OrchQueueEqualityA (one public name).",
        f"- Previous counted fixture vectors: {prev_fx}. Current: {ledger['counted_fixture_vector_count']}.",
        f"- Ledger counts: phases={ledger['phase_count']}, retain_true={ledger['retain_true_count']}, momentary={ledger['momentary_count']}, counted_fixture_vectors={ledger['counted_fixture_vector_count']}.",
        f"- Validation: shape-valid={report['shape-valid']}, source_checked_subset={report['source_checked_subset']}, source_exact={report['source_exact']}, sole_blocker_claim={report.get('sole_blocker_claim')}, unresolved={report['unresolved']}, design_approved={report.get('design_approved')}, implementation_authorized={report.get('implementation_authorized')}.",
        "",
        "## Retained notes",
        "",
    ]
    lines.extend(retained or ["- (none)"])
    lines.extend(["", "## Phase list changes this regen", ""])
    lines.extend(diffs or ["- No phase-id changes."])
    lines.append(historical.rstrip() + "\n" if historical else "")
    rendered = "\n".join(lines) + "\n"
    if rendered == prior:
        return
    changelog_path.write_text(rendered, encoding="utf-8")


