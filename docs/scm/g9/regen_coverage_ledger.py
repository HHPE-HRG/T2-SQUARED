def extract_literals(text: str, start_token: str) -> list[str]:
    """Extract string literals from a Schema.Literals([ ... ]) / array initializer.

    Agent: must stop at the matching `]` of the opener. Effect/TS often closes with
    `]);` (not `];`), so a naive split on `];` over-reads into following TaggedError
    strings (Bitbucket bug that polluted success-path A.operation).
    """
    idx = text.find(start_token)
    if idx < 0:
        return []
    open_bracket = text.find("[", idx)
    if open_bracket < 0:
        return []
    depth = 0
    end = None
    # Bound scan so a missing closer cannot walk the whole file.
    limit = min(len(text), open_bracket + 8000)
    for i in range(open_bracket, limit):
        c = text[i]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        return []
    chunk = text[open_bracket : end + 1]
    raw = re.findall(r'"([^"]+)"', chunk)
    out = []
    seen = set()
    for x in raw:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def extract_rpc_methods():
    rpc = (ROOT / "packages/contracts/src/rpc.ts").read_text()
    orch = (ROOT / "packages/contracts/src/orchestration.ts").read_text()
    name_map = dict(re.findall(r"^\s+([A-Za-z0-9_]+):\s+\"([^\"]+)\"", rpc, re.M))
    orch_chunk = orch[orch.find("ORCHESTRATION_WS_METHODS") : orch.find("} as const;") + 1]
    name_map.update(dict(re.findall(r"^\s+([A-Za-z0-9_]+):\s+\"([^\"]+)\"", orch_chunk, re.M)))

    def resolve(expr: str) -> str | None:
        expr = expr.strip()
        if expr.startswith('"') and expr.endswith('"'):
            return expr.strip('"')
        parts = expr.split(".")
        if len(parts) == 2:
            return name_map.get(parts[1])
        return None

    group_m = re.search(r"export const WsRpcGroup = RpcGroup\.make\((.*?)\);", rpc, re.S)
    group_symbols = re.findall(r"\b(Ws[A-Za-z0-9]+Rpc)\b", group_m.group(1) if group_m else "")
    registered: list[str] = []
    streams: list[str] = []
    for sym in group_symbols:
        m = re.search(rf"export const {sym} = Rpc\.make\(\s*([^,]+),", rpc)
        if not m:
            continue
        method = resolve(m.group(1))
        if not method:
            continue
        start = m.start()
        nxt = rpc.find("export const ", start + 10)
        body = rpc[start : nxt if nxt > start else start + 2500]
        registered.append(method)
        if re.search(r"stream:\s*true", body):
            streams.append(method)

    def uniq(xs):
        out = []
        seen = set()
        for x in xs:
            if x not in seen:
                seen.add(x)
                out.append(x)
        return out

    registered = uniq(registered)
    streams = uniq(streams)
    unaries = [m for m in registered if m not in streams]
    orch_unary = [
        "orchestration.dispatchCommand",
        "orchestration.getWorkflowScript",
        "orchestration.getTurnDiff",
        "orchestration.getFullThreadDiff",
        "orchestration.searchThreads",
        "orchestration.getArchivedShellSnapshot",
    ]
    orch_stream = ["orchestration.subscribeShell", "orchestration.subscribeThread"]
    ws_unary = [m for m in unaries if m not in orch_unary]
    return registered, unaries, streams, ws_unary, orch_unary, orch_stream


def extract_http_endpoints() -> dict[str, list[dict]]:
    text = (ROOT / "packages/contracts/src/environmentHttp.ts").read_text()
    groups = {
        "HTTP-META": "EnvironmentMetadataHttpApi",
        "HTTP-AUTH": "EnvironmentAuthHttpApi",
        "HTTP-ORCH": "EnvironmentOrchestrationHttpApi",
        "HTTP-PR": "EnvironmentPullRequestsHttpApi",
        "HTTP-CONNECT": "EnvironmentConnectHttpApi",
    }
    out = {}
    for key, cls in groups.items():
        m = re.search(rf"export class {cls}.*?\{{\}}", text, re.S)
        chunk = m.group(0) if m else ""
        found = re.findall(
            r"HttpApiEndpoint\.(get|post|put|delete)\(\s*\"([^\"]+)\",\s*\"([^\"]+)\"",
            chunk,
        )
        auth = set(
            re.findall(
                r"HttpApiEndpoint\.(?:get|post|put|delete)\(\s*\"([^\"]+)\".*?EnvironmentAuthenticatedAuth",
                chunk,
                re.S,
            )
        )
        out[key] = [
            {
                "member_id": name,
                "method": verb.upper(),
                "path": path,
                "authenticated": name in auth,
            }
            for verb, name, path in found
        ]
    return out


