def _ts_str(value: str) -> str:
    """JSON-encode a string so it is a valid TypeScript string literal."""
    return json.dumps(value, ensure_ascii=False)


def _ts_lit_union(values: list[str]) -> str:
    """Join distinct string values as a TypeScript string-literal union."""
    # Preserve ledger order; drop exact duplicates only.
    seen: set[str] = set()
    ordered: list[str] = []
    for v in values:
        if v in seen:
            continue
        seen.add(v)
        ordered.append(v)
    if not ordered:
        return _ts_str("")
    return " | ".join(_ts_str(v) for v in ordered)


def _sanitize_type_suffix(comm_id: str, phase_id: str) -> str:
    """Build a stable alphanumeric suffix for uniquifying colliding equality_type names."""
    raw = f"{comm_id}_{phase_id}".replace("-", "_").replace(".", "_")
    cleaned = re.sub(r"[^A-Za-z0-9_]", "", raw)
    if cleaned and cleaned[0].isdigit():
        cleaned = f"P{cleaned}"
    return cleaned or "Phase"


def _iter_ledger_phases(ledger: dict) -> list[tuple[dict, dict]]:
    """Flatten ledger rows into (row, phase) pairs in ledger order."""
    out: list[tuple[dict, dict]] = []
    for row in ledger.get("rows") or []:
        for phase in row.get("phases") or []:
            out.append((row, phase))
    return out


def _assign_equality_a_type_names(
    phases: list[tuple[dict, dict]],
) -> dict[tuple[str, str], str]:
    """Map (comm_id, phase_id) → unique TS type name for that phase's public A.

    Prefer ledger `equality_type` when the (A_field, domain) shape matches the
    first registration of that name. On shape collision, suffix with comm/phase.
    """
    names: dict[tuple[str, str], str] = {}
    # equality_type → (shape_key, assigned_type_name)
    registered: dict[str, tuple[tuple[str, tuple[str, ...]], str]] = {}
    for row, phase in phases:
        comm_id = row["comm_id"]
        phase_id = phase["phase_id"]
        a_field = phase["equality_projection_A"][0]
        domain_key = (
            "request_label"
            if phase["liveToEquality"]["finite_domain"] == "request_label"
            else "state_label"
        )
        domain = tuple(phase[domain_key])
        shape = (a_field, domain)
        base = phase["equality_type"]
        prior = registered.get(base)
        if prior is None:
            names[(comm_id, phase_id)] = base
            registered[base] = (shape, base)
        elif prior[0] == shape:
            names[(comm_id, phase_id)] = prior[1]
        else:
            unique = f"{base}_{_sanitize_type_suffix(comm_id, phase_id)}"
            names[(comm_id, phase_id)] = unique
    return names


def _phase_input_fields(phase: dict) -> list[tuple[str, list[str]]]:
    """Return ordered (field_name, literal_domain) pairs for capture `input`.

    Always includes the equality A field. When the complementary label domain
    has more than one member, also require that label so occurrence labels are
    fully determined (flag-resolved style phases).
    """
    a_field = phase["equality_projection_A"][0]
    finite = phase["liveToEquality"]["finite_domain"]
    fields: list[tuple[str, list[str]]] = []
    if finite == "request_label":
        fields.append((a_field, list(phase["request_label"])))
        if len(phase["state_label"]) > 1:
            fields.append(("state_label", list(phase["state_label"])))
    else:
        fields.append((a_field, list(phase["state_label"])))
        if len(phase["request_label"]) > 1:
            fields.append(("request_label", list(phase["request_label"])))
    return fields


def render_equality_a_ts(
    ledger: dict, type_names: dict[tuple[str, str], str]
) -> str:
    """Render g9EqualityA.generated.ts contents (closed named A union)."""
    lines: list[str] = [GENERATED_TS_HEADER]
    lines.append(
        "/** Agent: named public equality A types, one shape per ledger phase "
        "(shared name when shapes match). */\n"
    )
    emitted_defs: set[str] = set()
    union_members: list[str] = []
    for row, phase in _iter_ledger_phases(ledger):
        key = (row["comm_id"], phase["phase_id"])
        type_name = type_names[key]
        a_field = phase["equality_projection_A"][0]
        finite = phase["liveToEquality"]["finite_domain"]
        domain = (
            list(phase["request_label"])
            if finite == "request_label"
            else list(phase["state_label"])
        )
        if type_name not in emitted_defs:
            lines.append(
                f"/** Public A for {row['comm_id']} / {phase['phase_id']} "
                f"(ledger equality_type={phase['equality_type']!r}). */\n"
            )
            lines.append(f"export type {type_name} = {{\n")
            lines.append(f"  readonly {a_field}: {_ts_lit_union(domain)};\n")
            lines.append("};\n\n")
            emitted_defs.add(type_name)
        if type_name not in union_members:
            union_members.append(type_name)
    lines.append(
        "/** Closed union of named phase A types (Task 14 / RFC-017/019). "
        "Not a public Record<string, string> fallback. */\n"
    )
    lines.append("export type G9EqualityA =\n  | " + "\n  | ".join(union_members) + ";\n")
    return "".join(lines)


def render_capture_input_ts(
    ledger: dict, type_names: dict[tuple[str, str], str]
) -> str:
    """Render g9CaptureInput.generated.ts contents (184-member input union)."""
    lines: list[str] = [GENERATED_TS_HEADER]
    lines.append(
        'import type { G9EqualityA } from "./g9EqualityA.generated.ts";\n\n'
    )
    # Re-export A union so occurrence can import from one generated surface if needed.
    lines.append("export type { G9EqualityA };\n\n")

    pair_literals: list[str] = []
    member_types: list[str] = []
    for row, phase in _iter_ledger_phases(ledger):
        comm_id = row["comm_id"]
        phase_id = phase["phase_id"]
        type_name = type_names[(comm_id, phase_id)]
        fields = _phase_input_fields(phase)
        input_props = "\n".join(
            f"    readonly {name}: {_ts_lit_union(domain)};" for name, domain in fields
        )
        fdc = phase.get("fixture_driver_class")
        fdc_comment = (
            f" fixture_driver_class={fdc!r};"
            if fdc in ("declaration-absence", "dormant-prototype")
            else ""
        )
        member = (
            f"  /** {comm_id} / {phase_id}; A={type_name}; "
            f"retain={str(phase['retainCurrentAfterPublish']).lower()};"
            f"{fdc_comment} */\n"
            f"  | {{\n"
            f"      readonly comm_id: {_ts_str(comm_id)};\n"
            f"      readonly phase: {_ts_str(phase_id)};\n"
            f"      readonly input: {{\n{input_props}\n      }};\n"
            f"    }}"
        )
        member_types.append(member)
        pair_literals.append(
            f"  {{ comm_id: {_ts_str(comm_id)}, phase_id: {_ts_str(phase_id)} }}"
        )

    lines.append(
        "/** Closed union of all ledger (comm_id, phase) capture inputs (set-equal 184). */\n"
    )
    lines.append("export type G9CaptureOccurrenceInput =\n" + "\n".join(member_types) + ";\n\n")
    lines.append(
        "/** Ledger phase pairs in ledger order — Task 14 set-equality oracle. */\n"
    )
    lines.append(
        "export const G9_LEDGER_PHASE_PAIRS = [\n"
        + ",\n".join(pair_literals)
        + ",\n] as const;\n\n"
    )
    lines.append(
        "export type G9LedgerPhasePair = (typeof G9_LEDGER_PHASE_PAIRS)[number];\n"
    )
    return "".join(lines)


def write_generated_capture_ts(ledger: dict) -> None:
    """Emit Task 14 generated TS under apps/server/src/scm/ (G9-Generator-Owner)."""
    phases = _iter_ledger_phases(ledger)
    type_names = _assign_equality_a_type_names(phases)
    GENERATED_EQUALITY_A_TS.parent.mkdir(parents=True, exist_ok=True)
    GENERATED_EQUALITY_A_TS.write_text(
        render_equality_a_ts(ledger, type_names), encoding="utf-8"
    )
    GENERATED_CAPTURE_INPUT_TS.write_text(
        render_capture_input_ts(ledger, type_names), encoding="utf-8"
    )
    print(
        f"generated TS: {GENERATED_EQUALITY_A_TS.relative_to(ROOT)} + "
        f"{GENERATED_CAPTURE_INPUT_TS.relative_to(ROOT)} "
        f"({len(phases)} phases, {len(set(type_names.values()))} A type names)",
        flush=True,
    )


