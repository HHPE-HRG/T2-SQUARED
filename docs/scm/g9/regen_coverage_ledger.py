class AuthorizationError(Exception):
    """Present authorization.md failed required-body validation (RFC-022)."""


def _auth_field(text: str, name: str) -> str | None:
    match = re.search(rf"(?im)^\s*[-*]?\s*{re.escape(name)}\s*:\s*(.+?)\s*$", text)
    if not match:
        return None
    return match.group(1).strip()


def validate_authorization_body(text: str) -> list[str]:
    """Return validation errors; empty list means the body satisfies RFC-022."""
    errors: list[str] = []
    gate = _auth_field(text, "gate")
    date = _auth_field(text, "date")
    human = _auth_field(text, "human")
    scope = _auth_field(text, "scope")
    if gate != "G9":
        errors.append("authorization.md requires `gate: G9`")
    if not date or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
        errors.append("authorization.md requires `date: YYYY-MM-DD`")
    if not human:
        errors.append("authorization.md requires non-empty `human:`")
    # Accept ASCII hyphen as equivalent to en-dash in scope.
    scope_ok = scope in {AUTHORIZATION_REQUIRED_SCOPE, "WP1-WP8 runtime"}
    if not scope_ok:
        errors.append(f"authorization.md requires `scope: {AUTHORIZATION_REQUIRED_SCOPE}`")
    return errors


def resolve_implementation_authorized() -> bool:
    """Absent => false. Present+valid => true. Present+invalid => AuthorizationError."""
    if not AUTHORIZATION_MD.is_file():
        return False
    errors = validate_authorization_body(AUTHORIZATION_MD.read_text(encoding="utf-8"))
    if errors:
        raise AuthorizationError("; ".join(errors))
    return True


def implementation_authorized_flag() -> bool:
    """True only when authorization.md exists and passes RFC-022 body checks."""
    return resolve_implementation_authorized()


