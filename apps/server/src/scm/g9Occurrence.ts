/**
 * G9 occurrence freeze and capture result types (WP2 / Task 3 + Task 14).
 *
 * Intended: deep-freeze occurrences at the enqueue boundary; export fault class
 * and ledger-projected capture input / equality A unions (Task 14 / RFC-017).
 * Observed: freezeOccurrence freezes the object and equality_A; G9InvariantFault
 * carries _tag + code. G9CaptureOccurrenceInput / G9EqualityA are generated
 * closed unions set-equal to coverage-ledger phases (G9-Generator-Owner).
 *
 * Does not own FIFO admit or promotion. Does not authorize G10.
 * Does not flip g9toG10Authorized.
 */
import type * as Effect from "effect/Effect";

import type { G9EqualityA, G9OrchQueueEqualityA } from "./g9EqualityA.generated.ts";
import type { G9CaptureOccurrenceInput } from "./g9CaptureInput.generated.ts";

/** Overload episode reason (capacity path only). */
export type G9OverloadReason = "capacity";

/** G9 waker lifecycle states (Task 10). */
export type G9WakerState = "stopped" | "armed-idle" | "armed-in-flight" | "faulted";

/**
 * Stable fault codes for G9InvariantFault.
 * capture-defect / waker-defect are RFC-018 isolated boundaries — never reuse
 * preflight for those surfaces.
 */
export type G9FaultCode =
  | "placement"
  | "reserved-identity"
  | "authority-parent"
  | "w1-invalid"
  | "preflight"
  | "clock-overlap"
  | "sequence-overflow"
  | "capture-defect"
  | "waker-defect";

/**
 * Thrown (sync) G9 invariant fault. Not an Effect typed error until Effect.try.
 *
 * Parameters
 * ----------
 * code : G9FaultCode
 *     Stable code for latch / observation.
 * message : string
 *     Human-readable detail for agents.
 */
export class G9InvariantFault extends Error {
  readonly _tag = "G9InvariantFault";
  readonly code: G9FaultCode;
  constructor(code: G9FaultCode, message: string) {
    super(message);
    this.code = code;
    this.name = "G9InvariantFault";
  }
}

/**
 * Closed union of all 184 ledger (comm_id, phase) capture inputs (Task 14).
 * Agent: generated by regen_coverage_ledger.py — do not hand-maintain members.
 */
export type { G9CaptureOccurrenceInput };

/**
 * Public equality A for INV-T2-ORCH-QUEUE / queue-offered (ledger equality_type).
 * Re-exported from generated file so slice helpers keep a stable import path.
 */
export type { G9OrchQueueEqualityA };

/**
 * Generated closed union of named phase A types (Task 14 / RFC-017/019).
 * Not a public Record<string, string> fallback.
 */
export type { G9EqualityA };

/**
 * Live occurrence shape after capture projection.
 * Agent: Task 14 sole live shape for all 184 ledger phases (RFC-017).
 * equality_A is the generated closed named-A union (RFC-019).
 */
export interface G9Occurrence {
  readonly comm_id: string;
  readonly phase_id: string;
  readonly node_id: string;
  readonly origin_bus_id: string;
  readonly attempt_sequence: number;
  /** Agent: closed union from g9EqualityA.generated.ts (G9-Generator-Owner). */
  readonly equality_A: G9EqualityA;
  readonly semanticKind: "request" | "state";
  readonly request_label: string;
  readonly state_label: string;
  readonly retainCurrentAfterPublish: boolean;
}

/**
 * ORCH-QUEUE-narrow occurrence alias for slice helpers / tests.
 * Live coordinator accepts full G9Occurrence after Task 14.
 */
export type OrchQueueOccurrence = G9Occurrence & {
  readonly comm_id: "INV-T2-ORCH-QUEUE";
  readonly phase_id: "queue-offered";
  readonly equality_A: G9OrchQueueEqualityA;
};

/** Capture outcome. Never rejected-muted / rejected-withheld / invalid / fault. */
export type G9CaptureResult =
  | { readonly status: "enqueued"; readonly occurrence: G9Occurrence }
  | { readonly status: "rejected-capacity"; readonly attempt_sequence: number }
  | { readonly status: "rejected-bus-withheld"; readonly attempt_sequence: number };

/**
 * Sink for latched G9 faults (Task 6+). Error channel never.
 */
export interface G9FaultSink {
  readonly deliver: (fault: G9InvariantFault) => Effect.Effect<void, never>;
}

/**
 * Freeze an occurrence and its equality_A at the enqueue boundary.
 *
 * Intended: callers must not mutate after admit. Observed: Object.freeze on
 * both the occurrence and equality_A; returns the same reference.
 *
 * Parameters
 * ----------
 * occurrence : G9Occurrence
 *     Candidate built by admit's build(seq) callback.
 *
 * Returns
 * -------
 * G9Occurrence
 *     Frozen occurrence (and frozen equality_A).
 */
export const freezeOccurrence = (occurrence: G9Occurrence): G9Occurrence => {
  Object.freeze(occurrence.equality_A);
  return Object.freeze(occurrence);
};
